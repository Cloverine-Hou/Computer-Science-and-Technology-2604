/*
【问题描述】输入华氏温度 F 的值，求出对应的摄氏温度 C，并显示。华氏温度 F 与摄氏温度 C 的转化关系如下：C=5/9*（F-32）。
【输入形式】华氏温度 
【输出形式】摄氏温度
【样例输入1】
65
【样例输出1】
18.3333
【样例输入2】
32
【样例输出2】
0
【样例输入3】
150
【样例输出3】
65.5556
【提示】警惕任何输入都会让算术表达式计算结果为零。注意：若结果不为0则保留4位小数。
*/
#include <stdio.h>
int main(){
    double F=0.0;
    scanf("%lf",&F);
    double C = (5.0/9.0)*(F-32.0);
    if(C!=0){
        printf("%.4lf",C);
    } else {
        printf("0");
    }
}
